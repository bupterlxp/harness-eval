"""writing_program -- LLM (or mock) draft+revise -> response + revisions.

A two-pass writing loop: draft the answer, then revise it once. Each pass is a
single bounded LLM call (``llm.complete(..., timeout=...)``). The intermediate
draft is saved as an artifact so the trajectory shows the revision history.

If no LLM is wired in (``llm is None``) the program falls back to a
``MockLLMClient`` so it runs fully offline and deterministically -- the same
control flow, just a scripted model. This demonstrates that programs depend on
the ``LLMClient`` contract, not on any particular provider.

Run offline (uses the mock automatically):
    python -m harness_scaffold.adapters.cli \
        --task-json <task.json> \
        --program harness_scaffold/examples/writing_program.py \
        --out-dir /tmp/write
"""
from __future__ import annotations

from typing import Optional

from harness_scaffold.core.context import RuntimeContext
from harness_scaffold.core.errors import ErrorCode
from harness_scaffold.core.schemas import HarnessResult
from harness_scaffold.llm.mock import MockLLMClient
from harness_scaffold.tools.registry import ToolRegistry
from harness_scaffold.examples._common import make_result

MAX_REVISIONS = 1


def _fallback_llm(prompt: str) -> MockLLMClient:
    """Deterministic stand-in so the example runs without a real provider."""
    draft = (
        f"Draft response to: {prompt}\n\n"
        "This is an initial draft produced without a network model."
    )
    revised = (
        "# Response\n\n"
        f"Topic: {prompt}\n\n"
        "This is the revised, cleaned-up answer. (Generated by the offline "
        "mock model; wire in a real LLMClient for substantive content.)\n"
    )
    return MockLLMClient(scripted=[draft, revised], model="mock-writer")


async def _complete(ctx: RuntimeContext, llm, messages: "list[dict]") -> str:
    timeout = min(ctx.policy.max_llm_seconds, max(1.0, ctx.time_left()))
    ctx.trajectory.log_llm_call(model=getattr(llm, "model", None),
                                num_messages=len(messages))
    resp = await llm.complete(messages, timeout=timeout)
    ctx.trajectory.log_llm_result(
        model=getattr(llm, "model", None), usage=resp.usage,
        text_preview=resp.text[:200],
    )
    return resp.text


class WritingProgram:
    name: str = "writing"

    async def run(
        self,
        ctx: RuntimeContext,
        tools: ToolRegistry,
        llm: "Optional[object]",
    ) -> HarnessResult:
        ctx.trajectory.log_step(0, phase="start", note=self.name)
        prompt = ctx.task.prompt or "(no prompt)"

        used_mock = llm is None
        client = llm if llm is not None else _fallback_llm(prompt)

        try:
            # Pass 1: draft.
            ctx.step()
            ctx.check_abort(stage="draft")
            draft = await _complete(
                ctx,
                client,
                [
                    {"role": "system", "content": "You are a concise writer."},
                    {"role": "user", "content": f"Write a short answer to:\n{prompt}"},
                ],
            )
            draft_path = ctx.new_artifact_text("draft.md", draft)
            ctx.trajectory.log_artifact("draft.md", draft_path, kind="text")

            # Pass 2..N: revise.
            current = draft
            for i in range(1, MAX_REVISIONS + 1):
                ctx.step()
                ctx.check_abort(stage=f"revise-{i}")
                current = await _complete(
                    ctx,
                    client,
                    [
                        {"role": "system", "content": "Revise for clarity and brevity."},
                        {"role": "user", "content": f"Original task:\n{prompt}"},
                        {"role": "assistant", "content": current},
                        {"role": "user", "content": "Produce a final, polished version."},
                    ],
                )
                rev_path = ctx.new_artifact_text(f"revision_{i}.md", current)
                ctx.trajectory.log_artifact(f"revision_{i}.md", rev_path, kind="text")
        except Exception as e:  # noqa  (covers provider/timeout failures)
            err = ctx.new_artifact_json(
                "error.json",
                {
                    "error_code": ErrorCode.LLM_ERROR.value,
                    "message": f"writing loop failed: {type(e).__name__}: {e}",
                    "stage": self.name,
                    "details": None,
                    "recoverable": True,
                    "elapsed_seconds": 0.0,
                },
            )
            ans = ctx.new_artifact_text(
                "response.md",
                f"# {self.name}\n\nThe writing loop failed before producing a "
                "result.\n",
            )
            return make_result(ctx, status="llm_error", answer_path=ans,
                               error_path=err, metadata={"program": self.name})

        answer_path = ctx.new_artifact_text("response.md", current)
        ctx.trajectory.log_step(1, phase="done")

        return make_result(
            ctx,
            status="success",
            answer_path=answer_path,
            metadata={
                "program": self.name,
                "used_mock_llm": used_mock,
                "model": getattr(client, "model", None),
                "revisions": MAX_REVISIONS,
            },
        )


PROGRAM = WritingProgram()


def get_program() -> WritingProgram:
    return PROGRAM
